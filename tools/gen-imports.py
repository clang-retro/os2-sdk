#!/usr/bin/env python3
"""Make the import lists of the OS/2 API for the Watcom linkers.

    gen-imports.py 16 DEFDIR > lib/os2-16.lnk
    gen-imports.py 32 DEFDIR > lib/os2-32.lnk

DEFDIR holds .def files of the OS/2 system DLLs, one per DLL:

    LIBRARY DOSCALLS
    EXPORTS
        DosWrite    @282

as Open Watcom's bld/os2api/lib286 (OS/2 1.x) and lib386 (OS/2 2.x) have.
Each export becomes "import NAME DLL.ORDINAL". The 32-bit list leaves out
the 16-bit entry points (all upper case, such as DOS16WRITE or VIOWRTTTY),
which 32-bit code cannot call directly.
"""
import os
import re
import sys


def main():
    bits, defdir = sys.argv[1], sys.argv[2]
    print("# Imports of the OS/2 %s API, generated by tools/gen-imports.py."
          % ("1.x (16-bit)" if bits == "16" else "2.x (32-bit)"))
    print("# The linker keeps only the imports a program uses.")
    seen = set()
    for name in sorted(os.listdir(defdir)):
        if not name.endswith(".def"):
            continue
        lib = None
        lines = []
        with open(os.path.join(defdir, name)) as f:
            for line in f:
                m = re.match(r"\s*LIBRARY\s+(\S+)", line)
                if m:
                    lib = m.group(1).upper()
                    continue
                m = re.match(r"\s*(\w+)\s+@(\d+)", line)
                if not m or lib is None:
                    continue
                sym, ordinal = m.group(1), int(m.group(2))
                if bits == "32" and not re.search(r"[a-z]", sym):
                    continue
                if sym in seen:
                    continue
                seen.add(sym)
                lines.append("import %s %s.%d" % (sym, lib, ordinal))
        if lines:
            print("# " + lib)
            print("\n".join(lines))


if __name__ == "__main__":
    main()
